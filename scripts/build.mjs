import { build } from 'esbuild';

// Pi aliases the public pi-ai entrypoint, but not its internal helper paths.
// Bundle those helpers from the pinned development version; retain host APIs.
await build({
  entryPoints: ['src/extension.ts'],
  // .ts forces Pi's loader to apply host aliases instead of native ESM/local peers.
  outfile: 'extension.ts',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  external: ['undici', 'eventsource-parser', 'proper-lockfile'],
  plugins: [{
    name: 'pi-host-api',
    setup(build) {
      build.onResolve({ filter: /^@earendil-works\/pi-(ai|coding-agent|tui)$/ }, args => ({ path: args.path, external: true }));
    },
  }],
  banner: { js: '// Generated by npm run build. Includes MIT-licensed pi-ai helpers; see THIRD_PARTY_NOTICES.' },
});
